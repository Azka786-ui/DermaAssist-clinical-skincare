/**
 * Finds a product by its unique slug across all concerns.
 */
export function getProductBySlug(slug: string): RecommendedProduct | undefined {
  for (const concern of CONCERN_LIST) {
    const products = RECOMMENDED_CARE_DATA[concern];
    const found = products.find((p) => p.slug === slug);
    if (found) return found;
  }
  return undefined;
}
